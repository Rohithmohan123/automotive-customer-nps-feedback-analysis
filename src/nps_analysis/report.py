"""Build the analytical report (Markdown + PDF) from the computed findings.

The report is assembled as a list of blocks (headings, paragraphs, bullet lists, tables,
figures) and rendered twice, so the Markdown and PDF always say the same thing.
"""
from __future__ import annotations

from datetime import date
from pathlib import Path

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (Image, KeepTogether, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)

from . import config as C

TITLE = "Automotive Customer NPS & Feedback Analysis"
SUBTITLE = "Two-wheeler customer experience in Nigeria, Egypt, the Philippines and DR Congo: a demonstration on synthetic data"
DISCLAIMER = ("All data in this report is synthetic. It was generated by code in this repository to demonstrate the analysis method. "
              "It does not describe real customers, real survey results, any client engagement or the actual performance of TVS, Bajaj "
              "or Haojue. Brand names are used only to make the competitor-comparison workflow realistic.")


def _fmt(v: float, signed: bool = True) -> str:
    return f"{v:+.0f}" if signed else f"{v:.0f}"


def _sig_phrase(test: dict) -> str:
    return "statistically significant (p < 0.05)" if test["significant_5pct"] else f"not statistically significant (p = {test['p_value']:.2f})"


def build_blocks(f: dict) -> list[tuple]:
    o = f["overall"]
    bc = f["by_country"].sort_values("nps", ascending=False)
    best, worst = bc.iloc[0], bc.iloc[-1]
    gaps = f["gaps"]
    n_sig = int((gaps["p_adjusted_bh"] < 0.05).sum())
    n_sig_raw = int(gaps["significant_5pct"].sum())
    own = f["by_ownership"].set_index("ownership_band")
    usage = f["usage_test"]
    tenure = f["tenure_test"]
    agr = f["agreement"]
    log = f["log"].set_index("rule")["rows_affected"]
    raw_n, clean_n = int(log["Rows in raw export"]), int(log["Rows in clean dataset"])
    det_top = f["seg_mentions"].query("nps_segment == 'Detractor'").head(3)
    pro_top = f["seg_mentions"].query("nps_segment == 'Promoter'").head(3)
    brand_tbl = f["by_brand"]
    cat = f["by_category"]

    lead = (f["top_det_theme"].sort_values("pct_of_commented", ascending=False).groupby("country").head(1)
            .set_index("country").reindex(C.COUNTRIES))

    B: list[tuple] = []
    B += [("h1", "1. Executive summary"), ("p", f"<b>{DISCLAIMER}</b>")]
    B.append(("bullets", [
        f"Across {o.n:,} valid responses the overall NPS is <b>{_fmt(o.nps)}</b> (95% CI {_fmt(o.ci_low)} to {_fmt(o.ci_high)}): "
        f"{o.promoters:.0%} promoters, {o.passives:.0%} passives and {o.detractors:.0%} detractors.",
        f"The widest gap is between markets. {best['country']} is highest at {_fmt(best['nps'])} and {worst['country']} lowest at "
        f"{_fmt(worst['nps'])}, a gap of {best['nps'] - worst['nps']:.0f} points"
        + (" with non-overlapping confidence intervals." if best["ci_low"] > worst["ci_high"] else " (confidence intervals overlap)."),
        f"Advocacy changes with ownership duration: NPS is {_fmt(own.loc['0-6 months', 'nps'])} in the first six months and falls to "
        f"{_fmt(own.loc[f['worst_band'], 'nps'])} at {f['worst_band']}. This {tenure['difference']:.0f}-point drop is {_sig_phrase(tenure)}.",
        f"Commercial riders (taxi / delivery) score {abs(usage['difference']):.0f} points below personal commuters; the difference is {_sig_phrase(usage)}.",
        f"Brand differences are small. TVS, Bajaj and Haojue sit between {_fmt(brand_tbl['nps'].min())} and {_fmt(brand_tbl['nps'].max())} overall, and "
        f"{n_sig} of {len(gaps)} TVS-vs-competitor comparisons remain significant after correcting for multiple testing "
        f"({n_sig_raw} before correction). The data does not support claiming that one brand leads.",
        f"Detractors mostly talk about <b>{det_top.iloc[0]['themes'].lower()}</b> ({det_top.iloc[0]['pct_of_commented']:.0f}% of detractor comments) "
        f"and <b>{det_top.iloc[1]['themes'].lower()}</b> ({det_top.iloc[1]['pct_of_commented']:.0f}%). Promoters praise "
        f"<b>{pro_top.iloc[0]['themes'].lower()}</b> and <b>{pro_top.iloc[1]['themes'].lower()}</b>.",
    ]))

    B += [("h1", "2. Objectives and approach"), ("bullets", [
        "Measure NPS and customer satisfaction (CSAT) overall and by market, brand, ownership duration and usage type.",
        "Compare the focus brand (TVS) with competitors (Bajaj, Haojue) within each market, with significance tests.",
        "Identify recurring feedback themes from open-ended comments and link them to detractors and promoters.",
        "Translate the findings into prioritised, testable recommendations.",
    ]), ("p", "NPS = % promoters (scores 9-10) minus % detractors (0-6), on a scale of -100 to +100. Confidence intervals use the standard error of "
              "a three-category outcome: SE = sqrt[(p<sub>P</sub> + p<sub>D</sub> - NPS<super>2</super>) / n]. Differences between two groups are tested with a "
              "two-sided z-test. Because the brand comparison involves ten tests, p-values are also adjusted with the Benjamini-Hochberg "
              "false-discovery-rate method. Segments with fewer than "
              f"{C.MIN_SEGMENT_N} responses are flagged as low-sample.")]

    B += [("h1", "3. Data and cleaning"), ("p",
          f"The raw export holds {raw_n:,} rows: {o.n:,} unique respondents remain after cleaning ({clean_n / raw_n:.1%}). Rows were dropped only where the "
          "respondent could not be identified or the NPS answer was unusable. Other problems (invalid satisfaction scores, implausible ownership "
          "durations, out-of-period dates) were set to missing so the rest of the response could still be used. Every rule is logged:"),
          ("table", f["log"].rename(columns={"rule": "Rule", "rows_affected": "Rows", "action": "Action"}), [9.2, 1.6, 6.2])]

    B += [("pagebreak",), ("h1", "4. Overall NPS"), ("img", f["figs"]["score_distribution"]),
          ("p", f"Mean CSAT is {f['df']['satisfaction_score'].mean():.2f} out of 5. CSAT and likelihood to recommend are strongly related "
                f"(Spearman rho = {f['csat_corr']:.2f}), but CSAT alone does not identify promoters: many customers who rate satisfaction 4/5 are still passives."),
          ("img", f["figs"]["csat_vs_nps"])]

    B += [("h1", "5. Satisfaction by market"), ("img", f["figs"]["nps_by_country"]),
          ("table", f["by_country"][["country", "n", "promoters_pct", "passives_pct", "detractors_pct", "nps", "ci_low", "ci_high", "mean_csat"]]
           .rename(columns={"country": "Market", "promoters_pct": "Prom %", "passives_pct": "Pass %", "detractors_pct": "Det %", "nps": "NPS",
                            "ci_low": "CI low", "ci_high": "CI high", "mean_csat": "CSAT"}), None),
          ("img", f["figs"]["segment_mix_country"]),
          ("p", f"{worst['country']} combines the highest detractor share ({worst['detractors_pct']:.0f}%) with the lowest promoter share "
                f"({worst['promoters_pct']:.0f}%). {best['country']} has the most promoters ({best['promoters_pct']:.0f}%).")]

    B += [("pagebreak",), ("h1", "6. Competitor comparison"), ("img", f["figs"]["brand_country"]), ("img", f["figs"]["competitor_gaps"])]
    sig_rows = gaps[gaps["p_adjusted_bh"] < 0.05]
    # Minimum detectable effect for the per-market comparisons: (1.96 + 0.84) x typical SE of a difference
    per_market = gaps[gaps["country"] != "All markets"]
    mde = float(((per_market["ci_high"] - per_market["ci_low"]) / (2 * 1.96)).median() * 2.8)
    if len(sig_rows):
        txt = "; ".join(f"{r.country}: TVS vs {r.competitor} {r.difference:+.0f}" for r in sig_rows.itertuples())
        B.append(("p", f"Differences that remain significant after the false-discovery-rate correction: {txt}."))
    else:
        biggest = gaps.reindex(gaps["difference"].abs().sort_values(ascending=False).index).iloc[0]
        B.append(("p", f"No TVS-vs-competitor difference is significant after correcting for multiple comparisons. The largest observed gap is "
                       f"{biggest['difference']:+.0f} points (TVS vs {biggest['competitor']} in {biggest['country']}, 95% CI "
                       f"{biggest['ci_low']:+.0f} to {biggest['ci_high']:+.0f}). With roughly 200-350 owners per brand per market, the survey can only "
                       f"reliably detect gaps of about {mde:.0f} NPS points or more (80% power, 5% significance). Smaller real differences would need larger samples."))
    B.append(("table", gaps[["country", "competitor", "nps_a", "nps_b", "difference", "ci_low", "ci_high", "p_value", "p_adjusted_bh"]]
              .rename(columns={"country": "Market", "competitor": "Competitor", "nps_a": "TVS NPS", "nps_b": "Comp. NPS", "difference": "Gap",
                               "ci_low": "CI low", "ci_high": "CI high", "p_value": "p", "p_adjusted_bh": "p (FDR)"}), None))

    B += [("pagebreak",), ("h1", "7. Ownership duration and usage"), ("img", f["figs"]["ownership"]),
          ("table", f["by_ownership"][["ownership_band", "n", "nps", "ci_low", "ci_high", "mean_csat", "low_sample"]]
           .rename(columns={"ownership_band": "Ownership", "nps": "NPS", "ci_low": "CI low", "ci_high": "CI high", "mean_csat": "CSAT", "low_sample": "Low n"}), None),
          ("p", f"The dip at {f['worst_band']} matches the period when owners typically face their first major service and warranty expiry, so "
                "after-sales experience in year two is a likely lever. This is a hypothesis to test, not something this data proves. "
                "The 'Unknown' band holds respondents whose ownership answer was invalid; it is flagged as low-sample."),
          ("table", f["by_usage"][["usage_type", "n", "promoters_pct", "detractors_pct", "nps", "ci_low", "ci_high"]]
           .rename(columns={"usage_type": "Usage", "promoters_pct": "Prom %", "detractors_pct": "Det %", "nps": "NPS", "ci_low": "CI low", "ci_high": "CI high"}), None)]

    B += [("pagebreak",), ("h1", "8. Feedback themes"), ("p",
          "Comments were tagged with a transparent keyword dictionary (src/nps_analysis/themes.py), independently of the category the respondent "
          f"selected. The selected category matches the comment text for {agr['category_matches_text']}% of the {agr['responses_with_comment']:,} commented "
          f"responses, and {agr['untagged_comments']} comments were too vague to tag (e.g. 'Not happy.'). Coding the text, rather than relying only "
          "on the category field, avoids misreading the drivers."),
          ("img", f["figs"]["detractor_themes"])]
    lead_txt = "; ".join(f"{c}: {r['themes'].lower()} ({r['pct_of_commented']:.0f}%)" for c, r in lead.iterrows())
    B.append(("p", f"Leading detractor theme by market: {lead_txt}."))
    B += [("img", f["figs"]["promoter_themes"]),
          ("table", pd.concat([f["det_terms"].head(8).reset_index(drop=True).rename(columns={"term": "Detractor phrase", "count": "Count"}),
                               f["promo_terms"].head(8).reset_index(drop=True).rename(columns={"term": "Promoter phrase", "count": "Count "})], axis=1), None),
          ("img", f["figs"]["category_nps"]),
          ("p", f"By recorded category, responses filed under '{cat.iloc[0]['feedback_category']}' have the lowest NPS ({_fmt(cat.iloc[0]['nps'])}) and "
                f"'{cat.iloc[-1]['feedback_category']}' the highest ({_fmt(cat.iloc[-1]['nps'])}).")]

    B += [("img", f["figs"]["monthly"])]

    # Sample size per group to detect a 10-point NPS gap: n = 2 * var * ((1.96 + 0.84) / 0.10)^2, var on the -1..1 scale
    var = o.promoters + o.detractors - (o.nps / 100) ** 2
    n_needed = round(2 * var * (2.8 / 0.10) ** 2, -1)
    B += [("pagebreak",), ("h1", "9. Recommendations"), ("p",
          "Ranked by how often the theme appears in detractor comments. Each should be piloted and measured (e.g. a before/after NPS read in the "
          "affected market), not rolled out on this analysis alone.")]
    B.append(("bullets", [f"<b>{a['theme']}</b> (most cited in {', '.join(a['lead_markets']) or 'several markets'}): {a['action']}" for a in f["actions"]]
                       + [f"<b>Year-two retention:</b> add a proactive check-up offer around months 12-18, when NPS is lowest.",
                          f"<b>Commercial riders:</b> design a fleet / high-mileage service plan, since commercial users score lower than personal users.",
                          f"<b>Measurement:</b> to detect brand gaps of about 10 NPS points within a market, plan for roughly {n_needed:,.0f} responses per brand per market "
                          "(80% power, 5% significance), and keep the open-ended question, because it explains the score."]))

    B += [("h1", "10. Method check and limitations"), ("p",
          "Because the data is synthetic, the generator's built-in assumptions are known. Checking whether the analysis recovers them shows the method "
          "works. It does not mean the results describe a real market."),
          ("table", f["method_check"].rename(columns=str.capitalize), [6.5, 6.8, 2.8]),
          ("bullets", [
              "Synthetic data: effect sizes, comments and market mixes are assumptions (documented in docs/synthetic_data_design.md).",
              "Comment templates are simpler than real free text. Real comments would need a larger dictionary, translation (Arabic, French, Filipino) "
              "or a trained classifier.",
              "Cross-sectional survey: ownership-duration effects compare different customers, not the same customers over time.",
              "No weighting: in a real study, results would be weighted to each market's sales mix and checked for non-response bias by survey channel.",
          ])]
    return B


# ---------------------------------------------------------------------------- Markdown

def _md_table(df: pd.DataFrame) -> str:
    d = df.copy()
    for c in d.columns:
        if d[c].dtype == bool:
            d[c] = d[c].map({True: "yes", False: "no"})
    header = "| " + " | ".join(map(str, d.columns)) + " |"
    sep = "|" + "|".join("---" for _ in d.columns) + "|"
    rows = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |" for r in d.itertuples(index=False)]
    return "\n".join([header, sep, *rows])


def _md_text(s: str) -> str:
    return (s.replace("<b>", "**").replace("</b>", "**").replace("<sub>", "").replace("</sub>", "")
            .replace("<super>2</super>", "²").replace("<super>", "^").replace("</super>", ""))


def to_markdown(blocks: list[tuple], path: Path) -> None:
    out = [f"# {TITLE}", f"*{SUBTITLE}*", "", f"Generated {date.today():%d %B %Y} by `run_pipeline.py`.", ""]
    for b in blocks:
        kind = b[0]
        if kind == "h1":
            out += ["", f"## {b[1]}", ""]
        elif kind == "p":
            out += [_md_text(b[1]), ""]
        elif kind == "bullets":
            out += [f"- {_md_text(x)}" for x in b[1]] + [""]
        elif kind == "table":
            out += [_md_table(b[1]), ""]
        elif kind == "img":
            rel = Path("..") / Path(b[1]).relative_to(C.ROOT)
            out += [f"![{Path(b[1]).stem}]({rel.as_posix()})", ""]
    path.write_text("\n".join(out), encoding="utf-8")


# ---------------------------------------------------------------------------- PDF

INK, MUTED, LINE, ACCENT = colors.HexColor("#0b0b0b"), colors.HexColor("#6b6a66"), colors.HexColor("#e1e0d9"), colors.HexColor("#2a78d6")


def _styles():
    ss = getSampleStyleSheet()
    base = ParagraphStyle("base", parent=ss["Normal"], fontName="Helvetica", fontSize=9.6, leading=13.6, textColor=INK, alignment=TA_LEFT, spaceAfter=6)
    return {
        "title": ParagraphStyle("title", parent=base, fontName="Helvetica-Bold", fontSize=21, leading=25, spaceAfter=8),
        "subtitle": ParagraphStyle("subtitle", parent=base, fontSize=11, leading=15, textColor=MUTED, spaceAfter=18),
        "h1": ParagraphStyle("h1", parent=base, fontName="Helvetica-Bold", fontSize=14, leading=18, spaceBefore=12, spaceAfter=8, textColor=INK),
        "p": base,
        "bullet": ParagraphStyle("bullet", parent=base, leftIndent=12, bulletIndent=2, spaceAfter=4),
        "cell": ParagraphStyle("cell", parent=base, fontSize=7.6, leading=9.6, spaceAfter=0),
        "cellh": ParagraphStyle("cellh", parent=base, fontName="Helvetica-Bold", fontSize=7.6, leading=9.6, spaceAfter=0, textColor=MUTED),
        "box": ParagraphStyle("box", parent=base, fontSize=9, leading=12.5, textColor=colors.HexColor("#52514e")),
    }


def _pdf_table(df: pd.DataFrame, st, widths_cm: list[float] | None, avail: float) -> Table:
    d = df.copy()
    for c in d.columns:
        if d[c].dtype == bool:
            d[c] = d[c].map({True: "yes", False: "no"})
    data = [[Paragraph(str(c), st["cellh"]) for c in d.columns]]
    data += [[Paragraph("" if pd.isna(v) else str(v), st["cell"]) for v in r] for r in d.itertuples(index=False)]
    widths = [w * cm for w in widths_cm] if widths_cm else [avail / len(d.columns)] * len(d.columns)
    t = Table(data, colWidths=widths, repeatRows=1, hAlign="LEFT")
    t.setStyle(TableStyle([
        ("LINEBELOW", (0, 0), (-1, 0), 0.8, colors.HexColor("#c3c2b7")),
        ("LINEBELOW", (0, 1), (-1, -1), 0.3, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3),
    ]))
    return t


def _page(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(2 * cm, 1.2 * cm, "Synthetic data - demonstration only. Not real customer, client or brand results.")
    canvas.drawRightString(A4[0] - 2 * cm, 1.2 * cm, f"Page {doc.page}")
    canvas.restoreState()


def to_pdf(blocks: list[tuple], path: Path) -> None:
    st = _styles()
    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=1.8 * cm, bottomMargin=2 * cm,
                            title=TITLE, author="Rohith Mohan", subject="Synthetic NPS analysis demonstration")
    avail = A4[0] - 4 * cm
    story = [Paragraph(TITLE, st["title"]), Paragraph(SUBTITLE, st["subtitle"]),
             Paragraph(f"Generated {date.today():%d %B %Y}. Source code, data and every table: see the repository README.", st["box"]), Spacer(1, 8)]
    for b in blocks:
        kind = b[0]
        if kind == "h1":
            story.append(Paragraph(b[1], st["h1"]))
        elif kind == "p":
            story.append(Paragraph(b[1], st["p"]))
        elif kind == "bullets":
            story += [Paragraph(x, st["bullet"], bulletText="•") for x in b[1]]
            story.append(Spacer(1, 4))
        elif kind == "table":
            story += [_pdf_table(b[1], st, b[2], avail), Spacer(1, 10)]
        elif kind == "img":
            from PIL import Image as PILImage
            with PILImage.open(b[1]) as im:
                w, h = im.size
            width = avail
            max_h = 10.5 * cm
            if width * h / w > max_h:
                width = max_h * w / h
            story.append(KeepTogether([Image(str(b[1]), width=width, height=width * h / w), Spacer(1, 8)]))
        elif kind == "pagebreak":
            story.append(PageBreak())
    doc.build(story, onFirstPage=_page, onLaterPages=_page)


def write_reports(findings: dict) -> tuple[Path, Path]:
    C.REPORTS.mkdir(parents=True, exist_ok=True)
    blocks = build_blocks(findings)
    md, pdf = C.REPORTS / "nps_analysis_report.md", C.REPORTS / "nps_analysis_report.pdf"
    to_markdown(blocks, md)
    to_pdf(blocks, pdf)
    return md, pdf
